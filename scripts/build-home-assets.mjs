// Generate the offline classic-script payload from the unmodified upstream PNGs.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const assets = {
  genshinPrimary: 'gi_note_resin', hsrPrimary: 'hsr_note_trailblazePower',
  zzzPrimary: 'zzz_note_battery',
};
const revision = '29a063c4d906d9f02954ddf1f422e9a4d087aa59';
const base = `https://raw.githubusercontent.com/pizza-studio/PizzaHelperUnited/${revision}/Packages/PZKit/Sources/PZAccountKit/Resources/Assets.xcassets/DailyNoteIcons`;
const sources = {}, urls = {};
for (const [key, name] of Object.entries(assets)) {
  const bytes = readFileSync(new URL(`../card/assets/${name}.png`, import.meta.url));
  sources[key] = `data:image/png;base64,${bytes.toString('base64')}`;
  urls[`${name}.png`] = `${base}/${name}.imageset/${name}.png`;
}
writeFileSync(new URL('../card/home-assets.js', import.meta.url),
  '// Generated by scripts/build-home-assets.mjs. Artwork copyright miHoYo / HoYoverse; see assets/sources.json.\n' +
  '(function () { var root = typeof globalThis !== "undefined" ? globalThis : typeof window !== "undefined" ? window : this;\n' +
  `root.HoyoCardAssets = ${JSON.stringify(sources)};\n})();\n`);
writeFileSync(new URL('../card/assets/sources.json', import.meta.url), JSON.stringify({
  upstream: 'https://github.com/pizza-studio/PizzaHelperUnited', revision,
  copyright: 'Game artwork: miHoYo / HoYoverse. Not licensed under AGPL by this project.', files: urls,
}, null, 2) + '\n');
console.log(`Bundled ${Object.keys(sources).length} icons into ${fileURLToPath(new URL('../card/home-assets.js', import.meta.url))}`);
